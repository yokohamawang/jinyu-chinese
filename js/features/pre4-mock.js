  function toneOptions(pinyin) {
    const marks = ['\u0304','\u0301','\u030c','\u0300'];
    const base = pinyin.normalize('NFD');
    const position = base.search(/[\u0304\u0301\u030c\u0300]/);
    return marks.map(mark => (base.slice(0,position) + mark + base.slice(position+1)).normalize('NFC'))
      .filter(option => option !== pinyin);
  }

